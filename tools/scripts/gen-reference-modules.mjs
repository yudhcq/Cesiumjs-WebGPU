#!/usr/bin/env node
/**
 * `tools/scripts/gen-reference-modules.mjs` — write the frozen reference module pair
 * `webgpu/wgsl/globe-vs.wgsl` + `webgpu/wgsl/globe-fs.wgsl` (tasks.md T069).
 *
 *   node tools/scripts/gen-reference-modules.mjs [--check]
 *
 * Why this artifact exists:
 *   - the `wgsl/leaves/**` files are **templates** (they carry `#if` directives WGSL does not have),
 *     so nothing can hand them to a WGSL validator directly. The reference pair is what the emitter
 *     produces for the MVP golden configuration — a complete, template-free module pair that
 *     `naga --input-kind wgsl` (or any other module-level validator) can consume, and that a human
 *     can review as "path B 人工定稿" (contract R3/R7: the WGSL library lives in the backend layer);
 *   - architecture rule A10 pairs every `*-vs.wgsl` with a `*-fs.wgsl` in the same directory and
 *     checks the fragment input locations against the vertex outputs, so the static half of the
 *     varying contract has a real subject;
 *   - `--check` runs inside the unit suite, so the pair can never silently drift from the emitter.
 *
 * Zero dependencies beyond the workspace; Node-only, cross-platform.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { baseSources, enumerateMarginals, loadProduction } from "../../tools/shader-model.mjs";
import { repoPath } from "../../tests/support/repo.mjs";

/** The MVP golden configuration — the same selection `tools/shader-verify.mjs --variants=mvp` renders. */
export const GOLDEN_SELECTION = {
  textureUnits: "1",
  quantization: "float",
  lighting: "daynight",
  groundAtmosphere: "none",
  fog: "none",
  ocean: "none",
  imageryOps: "none",
  tileLimitRectangle: "none",
  geodetic: "none",
};

const OUT_FILES = {
  vertex: "packages/cesium-webgpu/backend-webgpu/webgpu/wgsl/globe-vs.wgsl",
  fragment: "packages/cesium-webgpu/backend-webgpu/webgpu/wgsl/globe-fs.wgsl",
};

export async function buildReferenceModules() {
  const production = await loadProduction();
  const base = await baseSources();
  const all = production.variants.enumerateReachableVariants();
  const variant = all.find((candidate) => Object.entries(GOLDEN_SELECTION).every(([id, value]) => candidate.selection.some((entry) => entry.id === id && entry.value === value)));
  if (variant === undefined) throw new Error(`gen-reference-modules: the golden selection ${JSON.stringify(GOLDEN_SELECTION)} is not a reachable variant`);

  // The layout must be the union over the reachable space: the module is emitted once per variant but
  // the uniform struct is a single shared declaration (the CPU-side writer uses this very table). The
  // marginal subset is what the harness uses, and the harness asserts it equals the full cross-product
  // union — see `tools/shader-model.mjs` `enumerateMarginals`.
  const { assembleGlslForVariant, unionOfVariants } = await import("../../tools/shader-model.mjs");
  const { automaticUniformNames } = await import("../../tools/shader-model.mjs");
  const automaticUniforms = await automaticUniformNames();
  const layoutInputs = await unionOfVariants({ variants: enumerateMarginals(all), production, base, automaticUniforms });
  const layout = production.bindLayout.layoutUniforms(layoutInputs, { structName: "TerrainUniforms" });

  // Re-emit with the golden variant's OWN contract: the reference pair documents the golden
  // configuration, so it must carry the golden pairing rather than a witness variant's union.
  const glsl = assembleGlslForVariant(variant, {
    ShaderSourceClass: production.ShaderSource,
    base,
    fragments: production.fragments,
    destinationOf: production.variants.destinationOf,
  });
  const contract = production.varyingContract.deriveVaryingContract({ vertexSource: glsl.vertexSource, fragmentSource: glsl.fragmentSource, defines: variant.defines, variantKey: variant.id });
  const emission = production.emitter.emitTerrainWgsl({
    variantKey: variant.id,
    vertexGlsl: glsl.vertexSource,
    fragmentGlsl: glsl.fragmentSource,
    defines: variant.defines,
    textureUnits: production.fragments.textureUnitsFromDefines(variant.defines),
    flags: production.fragments.applyFlagsFromDefines(variant.defines),
    layout,
    sceneMode: variant.sceneMode,
  });
  if (!emission.ok) throw new Error(`gen-reference-modules: the golden variant did not emit: ${JSON.stringify(emission.diagnostics)}`);

  void contract;
  const banner = [
    "// ============================================================================================",
    "// cesium-webgpu WebGPU backend layer — frozen reference module pair (tasks.md T069).",
    "//",
    "// GENERATED by `node tools/scripts/gen-reference-modules.mjs`; the unit suite runs it with",
    "// `--check`, so this file can never silently drift from the emitter.",
    "//",
    `// Variant: ${variant.id}`,
    `// Defines: ${variant.defines.join(" ") || "(none)"}`,
    "// Layout: union over the MVP-reachable define space (53 struct members + 3 sampler bindings).",
    "//",
    "// Why it is checked in: `wgsl/leaves/**` are templates (`#if` directives that WGSL does not have),",
    "// so a module-level validator cannot read them. This pair is complete and template-free, which is",
    "// what `tools/scripts/check-wgsl.mjs` hands to `naga --input-kind wgsl`, and what architecture rule",
    "// A10 pairs up statically (`-vs` output locations vs `-fs` input locations).",
    "// ============================================================================================",
  ].join("\n");

  return {
    variant,
    layout,
    files: {
      vertex: `${banner}\n${emission.vertexModule}`,
      fragment: `${banner}\n${emission.fragmentModule}`,
    },
  };
}

const isMain = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.slice(2).includes("--check");
  const { files, variant, layout } = await buildReferenceModules();
  let stale = false;
  for (const [stage, relative] of Object.entries(OUT_FILES)) {
    const file = repoPath(relative);
    const expected = files[stage];
    if (check) {
      const onDisk = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
      if (onDisk !== expected) {
        process.stderr.write(`gen-reference-modules: ${relative} is stale — run \`node tools/scripts/gen-reference-modules.mjs\`\n`);
        stale = true;
      }
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, expected, "utf8");
      process.stdout.write(`gen-reference-modules: wrote ${relative} (${expected.length} bytes)\n`);
    }
  }
  if (check) {
    if (stale) process.exitCode = 1;
    else process.stdout.write(`gen-reference-modules: the reference pair is up to date (${variant.id}, ${layout.structSize}-byte uniform block)\n`);
  }
}
