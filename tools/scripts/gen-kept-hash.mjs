#!/usr/bin/env node
/**
 * T032 — `keptModulesHash` generator (contract fork-patch-layer.md §2 rule 4).
 *
 * Everything under `Source/Renderer/**` that is NOT listed in the replacement manifest is
 * consumed **byte-identically** from the installed upstream package. This tool records the
 * content hash of each of those modules (plus one aggregate) into the manifest, so a silent
 * upstream change to a file we still depend on shows up as an audit failure instead of a
 * runtime surprise.
 *
 * Usage:
 *   node tools/scripts/gen-kept-hash.mjs             # (re)write the hashes into the manifest
 *   node tools/scripts/gen-kept-hash.mjs --check     # fail if the recorded hashes drifted
 *   node tools/scripts/gen-kept-hash.mjs --print     # write nothing, print the current set
 *
 * Exit codes: 0 ok ("no drift"), 1 drift detected (`--check`), 2 misconfiguration.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

import {
  MANIFEST_PATH,
  REPO_ROOT,
  compareKeptModules,
  computeKeptModules,
  readPatchManifest,
  toPosix,
} from "../lib/patch-layer.mjs";

function parseArgv(argv) {
  const options = { check: false, print: false };
  for (const arg of argv) {
    if (arg === "--check") options.check = true;
    else if (arg === "--print") options.print = true;
    else throw new Error(`unknown argument "${arg}"`);
  }
  if (options.check && options.print) throw new Error("--check and --print are mutually exclusive");
  return options;
}

/**
 * Compare the manifest's recorded kept-module hashes with the installed upstream package.
 *
 * @param {object} [options]
 * @param {string} [options.root] repository root (fixtures pass their own)
 * @param {string} [options.manifestPath] absolute or repository-relative manifest path
 * @param {string} [options.engineRoot] installed `@cesium/engine` root
 */
export function checkKeptModules(options = {}) {
  const root = options.root ? path.resolve(options.root) : REPO_ROOT;
  const manifestPath = options.manifestPath
    ? path.isAbsolute(options.manifestPath)
      ? options.manifestPath
      : path.join(root, ...options.manifestPath.split("/"))
    : path.join(root, ...MANIFEST_PATH.split("/"));
  const manifest = readPatchManifest(root, manifestPath);
  if (manifest === null) {
    return { ok: false, reason: `replacement manifest not found: ${toPosix(path.relative(root, manifestPath))}`, computed: null, comparison: null };
  }
  const computed = computeKeptModules(options.engineRoot, manifest);
  const comparison = compareKeptModules(manifest, computed);
  return { ok: comparison.unchanged, reason: comparison.unchanged ? "recorded hashes match the installed upstream" : "kept-module drift", computed, comparison, manifestPath, manifest };
}

/** Write the freshly computed hashes into the manifest (the only write this tool performs). */
export function writeKeptModules(options = {}) {
  const root = options.root ? path.resolve(options.root) : REPO_ROOT;
  const manifestPath = options.manifestPath
    ? path.isAbsolute(options.manifestPath)
      ? options.manifestPath
      : path.join(root, ...options.manifestPath.split("/"))
    : path.join(root, ...MANIFEST_PATH.split("/"));
  const manifest = readPatchManifest(root, manifestPath);
  if (manifest === null) throw new Error(`replacement manifest not found: ${toPosix(path.relative(root, manifestPath))}`);
  const computed = computeKeptModules(options.engineRoot, manifest);

  manifest.keptModulesHash = computed.aggregate;
  manifest.keptModules = computed.hashes;
  manifest.keptModulesAlgorithm = computed.algorithm;
  manifest.keptModulesCount = computed.modules.length;
  manifest.keptModulesRecordedAt = new Date().toISOString();
  manifest.keptModulesNote =
    "Generated by tools/scripts/gen-kept-hash.mjs: content hash of every Renderer/** module that is NOT listed in entries[] " +
    "(the modules consumed byte-identically from the installed upstream package). tools/audit-patch-scope.mjs asserts keptModulesUnchanged " +
    "against this record; regenerate with the generator whenever an entry is added or removed.";
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  return { computed, manifestPath };
}

function main() {
  let options;
  try {
    options = parseArgv(process.argv.slice(2));
  } catch (error) {
    console.error(`gen-kept-hash: ${error.message}`);
    return 2;
  }

  try {
    if (options.print) {
      const result = checkKeptModules();
      if (result.computed === null) {
        console.error(`gen-kept-hash: ${result.reason}`);
        return 2;
      }
      const { comparison } = result;
      console.log(`kept modules: ${result.computed.modules.length} (recorded ${comparison.recordedAggregate ?? "(none)"})`);
      console.log(`fresh aggregate: ${result.computed.aggregate}`);
      for (const module_ of result.computed.modules) console.log(`  ${module_}\t${result.computed.hashes[module_]}`);
      return 0;
    }

    if (options.check) {
      const result = checkKeptModules();
      if (result.ok) {
        console.log(`no drift (${result.computed.modules.length} kept module(s), ${result.computed.aggregate})`);
        return 0;
      }
      const { comparison } = result;
      console.error(`gen-kept-hash: ${result.reason}`);
      for (const module_ of comparison?.drifted ?? []) console.error(`  drifted: ${module_}`);
      for (const module_ of comparison?.modulesAdded ?? []) console.error(`  missing from the record: ${module_}`);
      for (const module_ of comparison?.modulesRemoved ?? []) console.error(`  recorded but no longer kept: ${module_}`);
      if (comparison && comparison.recordedAggregate !== comparison.computedAggregate) {
        console.error(`  aggregate ${comparison.recordedAggregate ?? "(none)"} -> ${comparison.computedAggregate}`);
      }
      return 1;
    }

    const { computed, manifestPath } = writeKeptModules();
    console.log(
      `gen-kept-hash: recorded ${computed.modules.length} kept module(s) (${computed.aggregate}) in ` +
        `${toPosix(path.relative(REPO_ROOT, manifestPath))}`,
    );
    return 0;
  } catch (error) {
    console.error(`gen-kept-hash: ${error.message}`);
    return 2;
  }
}

const invokedDirectly = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  process.exitCode = main();
}

export { main };
